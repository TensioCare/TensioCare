from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Integer, String, Text, func
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.orm import relationship as orm_relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.patient import PatientProfile
    from app.models.user import User


class CaregiverProfile(Base):
    """A family member / trusted person looking after exactly one patient."""

    __tablename__ = "caregiver_profiles"

    id: Mapped[int] = mapped_column(primary_key=True)
    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), unique=True, index=True
    )

    relationship: Mapped[str] = mapped_column(String(60), nullable=False)
    phone: Mapped[str | None] = mapped_column(String(32))
    notes: Mapped[str | None] = mapped_column(Text)

    # Caregivers log in with a code generated by the patient.
    login_code_hash: Mapped[str] = mapped_column(
        String(64), unique=True, index=True, nullable=False
    )
    claimed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    user: Mapped["User"] = orm_relationship(back_populates="caregiver_profile")
    links: Mapped[list["CaregiverPatient"]] = orm_relationship(
        back_populates="caregiver",
        cascade="all, delete-orphan",
        foreign_keys="CaregiverPatient.caregiver_id",
    )

    @property
    def first_name(self) -> str:
        return self.user.first_name

    @property
    def last_name(self) -> str:
        return self.user.last_name

    @property
    def patients(self) -> list["CaregiverPatient"]:
        """Alias used by the API schema: the patients this caregiver follows."""
        return self.links

    @property
    def status(self) -> str:
        """ "pending" until the code is used for the first time."""
        return "active" if self.claimed_at is not None else "pending"


class CaregiverPatient(Base):
    """Link between a caregiver and the single patient they follow.

    A patient can have many caregivers, but a caregiver has exactly one patient:
    ``caregiver_id`` is unique, so a second link for the same caregiver is
    rejected by the database.
    """

    __tablename__ = "caregiver_patients"

    caregiver_id: Mapped[int] = mapped_column(
        ForeignKey("caregiver_profiles.id", ondelete="CASCADE"),
        primary_key=True,
        unique=True,
    )
    patient_id: Mapped[int] = mapped_column(
        ForeignKey("patient_profiles.id", ondelete="CASCADE"), primary_key=True
    )

    # Escalation ring: 1 is called first, then 2, 3, ...
    priority: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    # How long this caregiver has to acknowledge before the next one is called.
    notify_after_minutes: Mapped[int] = mapped_column(
        Integer, default=15, nullable=False
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    caregiver: Mapped["CaregiverProfile"] = orm_relationship(
        back_populates="links", foreign_keys=[caregiver_id]
    )
    patient: Mapped["PatientProfile"] = orm_relationship(foreign_keys=[patient_id])

    @property
    def is_primary_contact(self) -> bool:
        """Backwards-compatible alias for "first in the escalation ring"."""
        return self.priority == 1

    @property
    def patient_user_id(self) -> int:
        return self.patient.user_id

    @property
    def first_name(self) -> str:
        return self.patient.user.first_name

    @property
    def last_name(self) -> str:
        return self.patient.user.last_name
